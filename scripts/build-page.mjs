// Bundles browser-side code (virtual clock, preview player, text probe) into strings for injection.
import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { build } from 'esbuild'

const root = new URL('../', import.meta.url)
const entries = {
  CLOCK_JS: 'src/page/clock.ts',
  PLAYER_JS: 'src/page/player.ts',
  PROBE_JS: 'src/page/probe.ts',
}
let out = '// Generated by scripts/build-page.mjs. Do not edit.\n'
for (const [name, entry] of Object.entries(entries)) {
  const path = new URL(entry, root).pathname
  if (!existsSync(path)) {
    out += `export const ${name} = ''\n`
    continue
  }
  const js = await build({
    entryPoints: [path],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: true,
    write: false,
  })
  out += `export const ${name} = ${JSON.stringify(js.outputFiles[0].text)}\n`
}
await writeFile(new URL('src/page/generated.ts', root), out)
